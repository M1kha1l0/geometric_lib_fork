
def area(a):
    '''
    Функция вычисления площади квадрата
        На вход подается число a>0 - сторона квадрата
        На выходе получаем квадрат числа а - площадь квадрата со стороной а
    '''
    return a * a


def perimeter(a):
    '''
    Функция вычисления периметра квадрата
        На вход подается число a>0 - сторона квадрата
        На выходе получаем 4 умноженное на а - периметр квадрата со стороной а
    '''
    return 4 * a
